// The JSON is the shared board/event source. Regenerate before adding a configuration migration.
import { readFile, writeFile } from "node:fs/promises";
const sql = [];
for (const [file, table] of [
  ["board", "board_v2"],
  ["events", "event_deck"],
]) {
  const data = JSON.parse(
    await readFile(new URL(`../src/data/${file}.json`, import.meta.url)),
  );
  sql.push(
    `create table campus_private.${table} (id integer primary key, data jsonb not null);`,
  );
  for (const row of data)
    sql.push(
      `insert into campus_private.${table} values (${row.index ?? row.id}, '${JSON.stringify(row).replaceAll("'", "''")}'::jsonb);`,
    );
}
await writeFile(
  new URL("../supabase/migrations/006_board_config.sql", import.meta.url),
  "-- Generated by scripts/generate-board-sql.mjs from src/data.\n" +
    sql.join("\n") +
    "\n",
);
